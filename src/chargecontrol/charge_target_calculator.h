// Рассчитывает целевое состояние зарядок по показаниям батареи.
//
// Логика:
//  - перегрев (isTemperatureOk == false): isChargeOn = false, все флаги
//    активных зарядок обнуляются;
//  - isMinimalCurrent == false: включаются все зарядки. Ток батареи при
//    этом не важен: ток <= 0 означает, что к устройству подключена внешняя
//    зарядка, которой нет в списке реле, — наши зарядки всё равно включаем;
//  - isMinimalCurrent == true: полным перебором комбинаций выбирается
//    комбинация с минимальной суммой номинальных токов, которая не меньше
//    тока батареи с запасом MIN_CURRENT_MARGIN (например, при токе 30 А
//    включаются зарядки 1 и 3: 25 + 15 = 40 А, а не 25 + 25 = 50 А). Если
//    даже все зарядки вместе не покрывают порог (ток 100 А при сумме 65 А),
//    включаются все доступные зарядки.
void calculateTargetState(const BatteryState& battery,
                          ChargeControlState& out,
                          bool isMinimalCurrent);
