#pragma once

#include <Arduino.h>
#include <daly-bms-uart.h>

// Обёртка над драйвером Daly BMS: хранит инстанс библиотеки и предоставляет доступ
// к показаниям без дублирования (телеметрия хранится в единственном экземпляре —
// в структурах get/alarm драйвера, что критично для 2 КБ RAM ATmega328P).
// Состояние БМС (телеметрия и тревоги) — это структуры get/alarm драйвера; BmsReader
// отдаёт их через getTelemetry()/getAlarms() (аналог getState()). Управляемой
// аппаратной части у BmsReader нет (БМС — внешнее устройство-источник), поэтому
// setState() отсутствует: точку входа для чтения задаёт update(). Дополнительно
// отслеживает флаг ошибки связи: БМС не отвечает по UART, если батарея разряжена
// и БМС отключилась.
class BmsReader {
private:
    // Инстанс драйвера Daly BMS, подключённый к Serial (единственное хранилище телеметрии).
    Daly_BMS_UART bms;

    // Флаг ошибки связи с БМС: true — БМС не отвечает по UART (батарея разряжена/отключилась).
    bool connectionError;

public:
    // Конструктор: привязывает драйвер к Serial (единственный UART у ATmega328P).
    BmsReader();

    // Тип структуры телеметрии драйвера (данные команд 0x90–0x97).
    typedef decltype(bms.get) Telemetry;

    // Тип структуры тревог драйвера (данные команды 0x98).
    typedef decltype(bms.alarm) Alarms;

    // Инициализирует последовательный порт (9600, 8N1) для связи с БМС.
    void init();

    // Опрашивает БМС (все команды 0x90–0x98); при неудаче проставляет флаг ошибки
    // связи, при успехе сбрасывает его. Возвращает true при успешном чтении.
    bool update();

    // True, если последнее чтение не удалось (БМС не отвечает по UART).
    bool isConnectionError() const;

    // Телеметрия последнего чтения: константная ссылка на структуру get драйвера.
    const Telemetry& getTelemetry() const;

    // Тревоги последнего чтения: константная ссылка на структуру alarm драйвера.
    const Alarms& getAlarms() const;
};
