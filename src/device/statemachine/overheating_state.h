#pragma once

#include "device_state_machine.h"

// Состояние «перегрев»: зарядка остановлена из-за превышения температуры.
// В это состояние переводит событие от датчика температуры (будет добавлено
// вместе с температурной логикой), а не смена тарифа.
struct OverheatingState : DeviceStateMachine {
    // Действие входа: фиксирует режим зарядки.
    void entry() override;

    // Пока перегрев не снят, смена тарифа игнорируется: зарядка остаётся
    // остановленной до восстановления после перегрева.
    void react(TariffEvent const&) override;
};
