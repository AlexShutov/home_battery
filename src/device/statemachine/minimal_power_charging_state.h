#pragma once

#include "device_state_machine.h"

// Состояние «средний тариф» (MIDDLE): электричество не самое дорогое,
// конфигурация зарядок зависит от уровня заряда батареи (гистерезис):
//  - заряд выше 60% — пользователю хватит заряда, все зарядки выключены;
//  - заряд ниже 50% — высокое потребление: поднимается флаг
//    isHighConsumption и батарея дозаряжается всеми зарядками до выхода
//    из состояния (сбросить флаг можно только выходом);
//  - в зоне 50–60% конфигурация зарядок не меняется.
struct MinimalPowerChargingState : DeviceStateMachine {
    MinimalPowerChargingState();

    // Действие входа: фиксирует режим зарядки и оценивает уровень заряда.
    void entry() override;

    // Действие выхода: сбрасывает флаг высокого потребления — он живёт
    // только внутри состояния.
    void exit() override;

    // Переоценка конфигурации зарядок при обновлении показаний батареи.
    void react(BatterySnapshotEvent const&) override;

    // Флаг высокого энергопотребления: заряд опустился ниже 50% при
    // среднем тарифе — дозаряжаем батарею полностью. Устанавливается
    // только здесь, сбрасывается только при выходе из состояния.
    bool isHighConsumption;

private:
    // Переоценивает конфигурацию зарядок по текущему уровню заряда.
    void evaluate();
};
