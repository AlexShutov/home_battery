#pragma once

#include "relay_state.h"

// Порт реле зарядок стейт-машины: машина управляет реле только через этот
// интерфейс. В прошивке реализуется настоящими реле (Relays); в нативных
// тестах может использоваться тестовая реализация.
class ChargingRelaysPort {
public:
    // Виртуальный деструктор: объекты порта используются полиморфно.
    virtual ~ChargingRelaysPort() {}

    // Применяет целевое состояние реле зарядок: реализация обязана обновить
    // и внутреннее состояние, и управляемую аппаратную часть (если есть).
    virtual void setState(const RelayState& newState) = 0;
};
