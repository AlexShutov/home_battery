#pragma once

#include <stdint.h>

// Дымовой тест стейт-машины зарядок на TinyFSM: циклически переключает пять
// состояний (выключены / все / 1 / 2 / 3 зарядки) без обращения к железу.
// Подтверждает сборку библиотеки и работу переходов на AVR и ESP32.

class TestChargingFsm {
public:
    // Запускает стейт-машину зарядок (выполняет вход в начальное состояние).
    void init();

    // Раз в TICKS_PER_EVENT вызовов отправляет машине событие перехода.
    void loop();

private:
    // Число вызовов loop() между событиями перехода.
    static const uint8_t TICKS_PER_EVENT = 10;

    // Счётчик вызовов loop() до следующего события перехода.
    uint8_t tick_counter_ = 0;
};
